class FastAPIService(Fixture):
    def setUp(self):
        super().setUp()
        self.write("app/main.py", textwrap.dedent("""\
            import os
            from fastapi import FastAPI
            from app.models import Item
            app = FastAPI()

            @app.get("/v1/items")
            def list_items() -> list:
                return []

            @app.post("/v1/items")
            def create(item: Item) -> Item:
                return item
        """))
        self.write("app/models.py", "class Item:\n    name: str = os.environ.get('X', '')\n")
        self.write("app/__init__.py", "")
        self.write("tests/test_main.py", "def test_x() -> None:\n    assert True\n" * 20)
        self.write("Dockerfile", "FROM python:3.12\n")
        self.write(".env.example", "X=1\n")
        self.write("uv.lock", "")
        self.write("README.md", "# svc\n")

    def test_interface_generated_contract(self):
        r = analyze(self.dir)
        iface = self.dim(r, "interface")
        self.assertEqual(iface.metrics["route_declarations"], 2)
        self.assertEqual(iface.level, 3)
        self.assertTrue(any(e.signal == "generated-spec" for e in iface.evidence))

    def test_mcp_server_adds_surface(self):
        self.write("app/mcp.py", "from mcp.server.fastmcp import FastMCP\nm = FastMCP('x')\n")
        self.assertEqual(self.dim(analyze(self.dir), "interface").level, 4)

    def test_mcp_client_is_not_a_surface(self):
        self.write("app/mcp.py", "from mcp import ClientSession\n")
        self.assertEqual(self.dim(analyze(self.dir), "interface").level, 3)

    def test_embeddability(self):
        emb = self.dim(analyze(self.dir), "embeddability")
        self.assertIn("container-image", emb.metrics["signals"])
        self.assertIn("env-config", emb.metrics["signals"])

    def test_legibility_typed(self):
        leg = self.dim(analyze(self.dir), "legibility")
        self.assertEqual(leg.metrics["typed_ratio"], 1.0)
        self.assertEqual(leg.metrics["import_cycles"], 0)

    def test_import_cycle(self):
        self.write("app/a.py", "from app import b\n")
        self.write("app/b.py", "from app import a\n")
        leg = self.dim(analyze(self.dir), "legibility")
        self.assertEqual(leg.metrics["import_cycles"], 1)

    def test_lazy_import_is_not_a_cycle(self):
        self.write("app/a.py", "from app import b\n")
        self.write("app/b.py", "def f():\n    from app import a\n")
        leg = self.dim(analyze(self.dir), "legibility")
        self.assertEqual(leg.metrics["import_cycles"], 0)

    def test_json_roundtrip(self):
        json.dumps(analyze(self.dir).to_dict())


class Libraries(Fixture):
    def test_typed_npm_library_is_a_contract(self):
        self.write("package.json", '{"name": "x", "main": "dist/index.js", "types": "dist/index.d.ts"}')
        self.write("src/index.ts", "export const f = (a: number): number => a;\n")
        iface = self.dim(analyze(self.dir), "interface")
        self.assertEqual(iface.level, 3)

    def test_untyped_js_library(self):
        self.write("package.json", '{"name": "x", "main": "index.js"}')
        self.write("index.js", "module.exports = function () {};\n")
        iface = self.dim(analyze(self.dir), "interface")
        self.assertEqual(iface.level, 1)
        self.assertTrue(any("type declarations" in g for g in iface.gaps))

    def test_go_main_only_is_not_a_library(self):
        self.write("go.mod", "module x\n")
        self.write("main.go", "// Copyright x\n\npackage main\nfunc main() {}\n")
        self.write("internal/cli/cli.go", "package cli\nfunc Run() {}\n")
        iface = self.dim(analyze(self.dir), "interface")
        self.assertEqual(iface.metrics["library_api"], [])

    def test_web_app_with_main_is_not_a_library(self):
        self.write("package.json", '{"name": "x", "main": "src/index.js"}')
        self.write("src/index.js", "document.body.innerHTML = '';\n")
        self.write("index.html", "<html></html>")
        self.assertEqual(self.dim(analyze(self.dir), "interface").metrics["library_api"], [])

    def test_testdata_spec_ignored(self):
        self.write("pkg/testdata/api.yaml", OPENAPI_V1)
        self.assertEqual(self.dim(analyze(self.dir), "interface").metrics["spec_files"], 0)


class SpecHistory(Fixture):
    def test_detects_removed_operation(self):
        self.git("init", "-q")
        self.write("api/openapi.yaml", OPENAPI_V1)
        self.write("server.js", "app.get('/v1/items', h)\napp.post('/v1/items', h)\n")
        self.commit("v1")
        self.git("tag", "v1.0.0")
        self.write("api/openapi.yaml", OPENAPI_V2)
        self.commit("drop delete")
        r = analyze(self.dir)
        stab = self.dim(r, "stability")
        self.assertEqual(stab.metrics["spec_operations_removed"], 1)
        self.assertEqual(stab.metrics["semver_tags"], 1)
        self.assertTrue(any("without deprecation" in g for g in stab.gaps))
        iface = self.dim(r, "interface")
        self.assertEqual(iface.metrics["spec_operations"], 3)
        self.assertGreaterEqual(iface.level, 3)


