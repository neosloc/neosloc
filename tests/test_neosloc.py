OPENAPI_V1 = textwrap.dedent("""\
    openapi: 3.0.0
    info:
      title: t
      version: 1.0.0
    paths:
      /v1/items:
        get:
          summary: list
        post:
          summary: create
      /v1/items/{id}:
        delete:
          summary: remove
    components: {}
""")
OPENAPI_V2 = OPENAPI_V1.replace("    delete:\n      summary: remove\n",
                                "    get:\n      summary: fetch\n")
assert OPENAPI_V2 != OPENAPI_V1


class Fixture(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.mkdtemp()

    def tearDown(self):
        shutil.rmtree(self.dir)

    def write(self, rel, text):
        path = os.path.join(self.dir, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as fh:
            fh.write(text)

    def git(self, *args):
        subprocess.run(["git", "-C", self.dir, *args], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    def commit(self, msg):
        self.git("add", "-A")
        self.git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", msg)

    def dim(self, report, key):
        return next(d for d in report.dimensions if d.key == key)


class SpecParsing(unittest.TestCase):
    def test_yaml_operations(self):
        self.assertEqual(openapi_operations(OPENAPI_V1, "api.yaml"),
                         {"GET /v1/items", "POST /v1/items", "DELETE /v1/items/{id}"})

    def test_json_operations(self):
        doc = {"openapi": "3.1.0", "paths": {"/a": {"get": {}, "parameters": []}}}
        self.assertEqual(openapi_operations(json.dumps(doc), "api.json"), {"GET /a"})

    def test_invalid_json(self):
        self.assertIsNone(openapi_operations("{nope", "api.json"))


class Cycles(unittest.TestCase):
    def test_detects_cycle(self):
        self.assertEqual(_cycles({("a", "b"), ("b", "a"), ("b", "c")}), [["a", "b"]])

    def test_acyclic(self):
        self.assertEqual(_cycles({("a", "b"), ("b", "c")}), [])


